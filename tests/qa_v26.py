from pathlib import Path
from playwright.sync_api import sync_playwright
import json,traceback,sys
ROOT=Path(__file__).resolve().parents[1]
HTML=(Path(sys.argv[1]) if len(sys.argv)>1 else ROOT.parent/'hamatate_v2_6_fixed_standalone.html').read_text('utf8')
checks=[];errors=[]
def check(name,func):
 try:func();checks.append((name,'PASS'));print('PASS',name,flush=True)
 except Exception as e:checks.append((name,'FAIL',str(e)[:300]));print('FAIL',name,str(e)[:300],flush=True)
def verify(cond):
 if not cond: raise AssertionError('Condition not met')
def K24_labels(pg):return pg.evaluate("K24.labels")
with sync_playwright() as p:
 b=p.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox'])
 pg=b.new_page(viewport={'width':1500,'height':950}, device_scale_factor=1)
 pg.on('pageerror',lambda e:errors.append(str(e)))
 pg.set_content(HTML,wait_until='domcontentloaded',timeout=40000)
 check('Localization runtime initialized',lambda:verify(pg.evaluate('typeof HAMATATE_I18N === "object"')))
 check('Knowledge data initialized',lambda:pg.wait_for_function('K24.ready',timeout=25000))
 check('English toggle and navigation',lambda: (pg.locator('[data-k26-lang="en"]').click(),pg.get_by_role('button',name='Corpus research').first.wait_for(timeout=4000)))
 check('English archive header',lambda:verify(pg.evaluate("document.querySelector('.v21-arrival h1')?.textContent.includes('Every performance')")))
 pg.evaluate("()=>v21OpenView('about')")
 check('About translation',lambda:pg.get_by_text('About the project').first.wait_for(timeout=8000))
 pg.evaluate("()=>v21OpenView('read')")
 check('Reader toolbar English',lambda:verify(pg.evaluate('''document.querySelector('[data-action=legend]')?.textContent === 'Notation key' ''')))
 check('Read source preserved Hebrew',lambda:verify(pg.evaluate("/[\\u0590-\\u05ff]/.test(document.querySelector('.text-body')?.textContent||'')")))
 check('Reader section controls translated',lambda:verify(pg.evaluate("document.querySelector('.text-segment header [data-action="+'"textrecord"'+"]')?.innerText==='Unit details'")))
 pg.evaluate("()=>v21OpenView('distant')")
 check('Distant toolbar English',lambda:pg.get_by_role('button',name='Network graph').first.wait_for(timeout=8500))
 check('Graph available',lambda:pg.locator('#k24Svg').first.wait_for(timeout=7500))
 def read_k24():return pg.evaluate('''()=>{const s=document.querySelector('#k24Svg'),r=s.getBoundingClientRect();return {width:r.width,height:r.height,ratio:r.width/r.height,view:s.viewBox.baseVal.width/s.viewBox.baseVal.height, plot:document.querySelector('#k24Plot').getAttribute('transform')};}''')
 a=read_k24()
 check('Whole SVG zoom enlarges chart',lambda: (pg.locator('[data-k24-zoom="in"]').click(),verify(read_k24()['width']>a['width']*1.15)))
 check('Uniform svg aspect ratio',lambda:verify(abs(read_k24()['ratio']-a['ratio'])<.05))
 check('Whole zoom not using inner plot scale',lambda:verify('scale' not in read_k24()['plot']))
 check('Labels enlarge independently',lambda:(pg.locator('[data-k24-zoom="label-in"]').click(),verify(K24_labels(pg)>1.15)))
 check('Whole SVG zoom out restores',lambda:(pg.locator('[data-k24-zoom="reset"]').click(),verify(abs(read_k24()['width']-a['width'])<4)))
 pg.get_by_role('button',name='Terms ↔ networks').first.click()
 check('Relations graph appears',lambda:pg.locator('.k25-diagram').wait_for(timeout=7000))
 def sz(sel):return pg.locator(sel).first.evaluate('(s)=>[s.getBoundingClientRect().width,s.getBoundingClientRect().height]')
 a=sz('.k25-diagram');pg.locator('[data-k25-zoom="in"]').click();v=sz('.k25-diagram')
 check('Relations width grows',lambda:verify(v[0]>a[0]*1.17))
 check('Relations height grows',lambda:verify(v[1]>a[1]*1.17))
 check('Relations preserve proportion',lambda:verify(abs(v[0]/v[1]-a[0]/a[1])<.02))
 check('Hebrew source term stays original',lambda:verify(pg.evaluate("/[\\u0590-\\u05ff]/.test(document.querySelector('.k25-term-node text')?.textContent||'')")))
 pg.screenshot(path=str(ROOT.parent/'hamatate_v2_6_fixed_english_relations.png'),full_page=False)
 check('Change back Hebrew',lambda:(pg.locator('[data-k26-lang="he"]').click(),pg.get_by_role('button',name='מפת הקשרים').first.wait_for(timeout=9000)))
 check('Hebrew source preserved',lambda:verify(pg.evaluate("document.documentElement.lang==='he'&&document.documentElement.dir==='rtl'")))
 pg.evaluate("()=>{ST.lens='actors';ST.networkMode='shared';v21OpenView('stage')}")
 pg.wait_for_timeout(600)
 check('Actor SVG wrapped in scroll viewport',lambda:verify(pg.locator('.k26-chart-shell .stage-network-svg').count()>=1))
 def actor():return sz('.k26-chart-shell .stage-network-svg')
 initial=actor();pg.locator('.k26-chart-shell [data-k26-chart="in"]').first.click();grown=actor()
 check('Actor graph width grows',lambda:verify(grown[0]>initial[0]*1.15))
 check('Actor graph height grows',lambda:verify(grown[1]>initial[1]*1.15))
 check('Actor SVG uniform scale',lambda:verify(abs(grown[0]/grown[1]-initial[0]/initial[1])<.025))
 pg.evaluate("()=>v21OpenView('read')")
 check('Read is still operational',lambda:pg.locator('.text-body').first.wait_for(timeout=8500))
 check('Footnotes unchanged',lambda:verify(pg.evaluate('Object.keys(D.footnotes).length===529')))
 pg.evaluate("()=>v21OpenView('materials')")
 check('Materials retained',lambda:pg.get_by_text('מפה וחומרים').first.wait_for(timeout=7500))
 pg.evaluate("()=>v21OpenView('audit')")
 check('Audit retained',lambda:verify(pg.locator('#content').inner_text()!=''))
 pg.evaluate("()=>HAMATATE_I18N.setLanguage('en')")
 check('Dynamic toolbar retains English after rerender',lambda:verify(pg.evaluate("document.querySelector('[data-view="+'"distant"'+"]')?.textContent.includes('Distant reading')")))
 pg.evaluate("()=>v21OpenView('distant')")
 check('Distant English after nav re-render',lambda:pg.get_by_role('button',name='Terms ↔ networks').first.wait_for(timeout=7500))
 check('No JS errors',lambda:verify(not errors))
 print('TOTAL',len(checks),'PASS',sum(x[1]=='PASS' for x in checks),'ERRORS',errors[:6],flush=True)
 (ROOT/'docs/QA_V2_6_FIXED.json').write_text(json.dumps({'checks':checks,'errors':errors},ensure_ascii=False,indent=2))
 b.close()
 if any(x[1]=='FAIL' for x in checks) or errors:raise SystemExit(1)
